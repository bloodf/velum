def L(en: str, pt: str) -> dict:
    return {"en": en, "pt-BR": pt}


def defn(
    *,
    template_id: str,
    source: str = "all",
    wake: str | None = None,
    dmin: int = 0,
    dmax: int = 10800,
    label: bool = True,
    language: str = "auto",
    notify: bool = True,
    post: str | None = None,
) -> dict:
    assert dmin <= dmax
    return {
        "wake_phrase": wake,
        "source_filter": source,
        "duration_min_seconds": dmin,
        "duration_max_seconds": dmax,
        "template_id": template_id,
        "auto_label_voice": label,
        "language": language,
        "notify": notify,
        "post_action": post,
    }


def T(
    slug: str,
    category: str,
    name_en: str,
    name_pt: str,
    desc_en: str,
    desc_pt: str,
    preview_en: str,
    preview_pt: str,
    definition: dict,
    icon: str | None = None,
) -> dict:
    return {
        "schema_version": SCHEMA_VERSION,
        "id": f"{category}.{slug}",
        "category": category,
        "icon": icon or CATEGORY_ICON[category],
        "name": L(name_en, name_pt),
        "description": L(desc_en, desc_pt),
        "preview": L(preview_en, preview_pt),
        "definition": definition,
    }


