def write_all() -> None:
    # Clear previous generated category dirs (keep schema/)
    for child in OUT.iterdir():
        if child.is_dir() and child.name != "schema":
            for f in child.glob("*.json"):
                f.unlink()
            # remove empty dirs later if needed

    ids: set[str] = set()
    by_cat: dict[str, int] = {}
    for t in TEMPLATES:
        tid = t["id"]
        if tid in ids:
            raise SystemExit(f"Duplicate id: {tid}")
        ids.add(tid)
        cat = t["category"]
        by_cat[cat] = by_cat.get(cat, 0) + 1
        d = t["definition"]
        if d["duration_min_seconds"] > d["duration_max_seconds"]:
            raise SystemExit(f"Bad duration range in {tid}")
        folder = OUT / cat
        folder.mkdir(parents=True, exist_ok=True)
        slug = tid.split(".", 1)[1]
        path = folder / f"{slug}.json"
        path.write_text(json.dumps(t, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"Wrote {len(TEMPLATES)} templates")
    for cat in sorted(by_cat):
        print(f"  {cat}: {by_cat[cat]}")
    if len(TEMPLATES) < 100:
        raise SystemExit(f"Need at least 100 templates, got {len(TEMPLATES)}")


if __name__ == "__main__":
    write_all()
