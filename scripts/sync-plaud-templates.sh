#!/usr/bin/env bash
# Mirror docs/templates/plaud_templates.jsonl into Kotlin + regenerate credits.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
JSONL="$ROOT/docs/templates/plaud_templates.jsonl"
OUT_KT="$ROOT/core/src/commonMain/kotlin/dev/velum/core/templates/PlaudTemplateCatalogData.kt"
CREDITS="$ROOT/docs/TEMPLATES_CREDITS.md"

mkdir -p "$(dirname "$OUT_KT")"
{
  echo 'package dev.velum.core.templates'
  echo
  echo '/**'
  echo ' * Auto-generated from docs/templates/plaud_templates.jsonl — do not edit by hand.'
  echo ' * Run: ./scripts/sync-plaud-templates.sh'
  echo ' */'
  echo 'object PlaudTemplateCatalogData {'
  echo -n '    const val JSONL: String = """'
  # Escape """ sequences in body text if any
  if [[ -f "$JSONL" ]]; then
    sed 's/"""/"\\""\\""/g' "$JSONL"
  fi
  echo '"""'
  echo '}'
} > "$OUT_KT"

# Credits via JVM unit test helper would need a full build; write a stub header + count here,
# then refine with Kotlin when available.
COUNT=0
if [[ -f "$JSONL" ]]; then
  COUNT=$(grep -c '[^[:space:]]' "$JSONL" || true)
fi

{
  echo '# Template credits'
  echo
  echo "Generated by \`scripts/sync-plaud-templates.sh\` from the built-in catalog."
  echo
  echo '## Velum originals'
  echo
  echo '| id | name | author | source |'
  echo '|---|---|---|---|'
  echo '| `velum.general` | Resumo geral | Velum | Velum |'
  echo '| `velum.meeting` | Ata de reunião | Velum | Velum |'
  echo '| `velum.call` | Resumo de ligação | Velum | Velum |'
  echo '| `velum.sales` | Chamada de vendas | Velum | Velum |'
  echo '| `velum.interview` | Entrevista | Velum | Velum |'
  echo '| `velum.consulting` | Sessão de consultoria | Velum | Velum |'
  echo '| `velum.education` | Aula / palestra | Velum | Velum |'
  echo '| `velum.speech` | Discurso / apresentação | Velum | Velum |'
  echo '| `velum.medical` | Consulta médica | Velum | Velum |'
  echo '| `velum.legal` | Reunião jurídica | Velum | Velum |'
  echo '| `velum.financial` | Reunião financeira | Velum | Velum |'
  echo '| `velum.estate` | Visita / negociação imobiliária | Velum | Velum |'
  echo '| `velum.construction` | Reunião de obra | Velum | Velum |'
  echo '| `velum.it` | Reunião técnica (TI) | Velum | Velum |'
  echo '| `velum.extractive` | Extração de itens | Velum | Velum |'
  echo
  echo '## Plaud templates (official + community)'
  echo
  if [[ "$COUNT" -eq 0 ]]; then
    echo '_Awaiting collected JSONL from Heitor — drop into `docs/templates/plaud_templates.jsonl` and re-run this script._'
  else
    echo "Shipped entries: **$COUNT** (see JSONL for author / official / sourceTemplateId)."
    echo
    echo 'Run a JVM test `PlaudTemplateCatalogTest.creditsMarkdown_listsAuthors` after sync to refresh the author table.'
  fi
  echo
} > "$CREDITS"

echo "Synced $COUNT Plaud JSONL line(s) → $OUT_KT and $CREDITS"
