#!/usr/bin/env bash
# Sync docs/templates JSONL → classpath assets + regenerate docs/TEMPLATES_CREDITS.md.
# Does NOT embed the catalog into a Kotlin string (lazy asset load instead).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PLAUD_JSONL="$ROOT/docs/templates/plaud_templates.jsonl"
CONTRIB_JSONL="$ROOT/docs/templates/velum_contributed.jsonl"
RES_DIR="$ROOT/core/src/commonMain/resources"
CREDITS="$ROOT/docs/TEMPLATES_CREDITS.md"

mkdir -p "$RES_DIR"
touch "$PLAUD_JSONL" "$CONTRIB_JSONL"
cp "$PLAUD_JSONL" "$RES_DIR/plaud_templates.jsonl"
cp "$CONTRIB_JSONL" "$RES_DIR/velum_contributed.jsonl"

PLAUD_COUNT=$(grep -c '[^[:space:]]' "$PLAUD_JSONL" || true)
CONTRIB_COUNT=$(grep -c '[^[:space:]]' "$CONTRIB_JSONL" || true)

python3 - "$PLAUD_JSONL" "$CONTRIB_JSONL" "$CREDITS" <<'PY'
import json, sys
from collections import Counter

plaud_path, contrib_path, credits_path = sys.argv[1:4]

def load_jsonl(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            rows.append(json.loads(line))
    return rows

plaud = load_jsonl(plaud_path)
contrib = load_jsonl(contrib_path)

velum = [
    ("velum.general", "Resumo geral"),
    ("velum.meeting", "Ata de reunião"),
    ("velum.call", "Resumo de ligação"),
    ("velum.sales", "Chamada de vendas"),
    ("velum.interview", "Entrevista"),
    ("velum.consulting", "Sessão de consultoria"),
    ("velum.education", "Aula / palestra"),
    ("velum.speech", "Discurso / apresentação"),
    ("velum.medical", "Consulta médica"),
    ("velum.legal", "Reunião jurídica"),
    ("velum.financial", "Reunião financeira"),
    ("velum.estate", "Visita / negociação imobiliária"),
    ("velum.construction", "Reunião de obra"),
    ("velum.it", "Reunião técnica (TI)"),
    ("velum.extractive", "Extração de itens"),
]

lines = []
lines.append("# Template credits")
lines.append("")
lines.append("Generated by `scripts/sync-plaud-templates.sh` from the built-in catalog.")
lines.append("")
lines.append("Plaud `author` / `official` fields are documented here for provenance.")
lines.append("The Velum app UI does **not** show Plaud author names or official badges.")
lines.append("In-app credit appears only for Velum PR contributions that set `contributor`.")
lines.append("")
lines.append("## Velum originals")
lines.append("")
lines.append("| id | name | author | source |")
lines.append("|---|---|---|---|")
for vid, name in velum:
    lines.append(f"| `{vid}` | {name} | Velum | Velum |")
lines.append("")
lines.append("## Velum PR contributions")
lines.append("")
if not contrib:
    lines.append("_None yet — see `CONTRIBUTING.md` (Template contributions)._")
else:
    lines.append("| id | name | contributor | github |")
    lines.append("|---|---|---|---|")
    for e in contrib:
        c = e.get("contributor") or {}
        lines.append(
            f"| `{e.get('id','')}` | {e.get('name','')} | {c.get('name','')} | {c.get('github','')} |"
        )
lines.append("")
lines.append("## Plaud templates (official + community)")
lines.append("")
if not plaud:
    lines.append(
        "_Awaiting collected JSONL — drop into `docs/templates/plaud_templates.jsonl` and re-run this script._"
    )
else:
    lines.append(f"Shipped entries: **{len(plaud)}**.")
    lines.append("")
    lines.append("| id | name | author | official | category | source |")
    lines.append("|---|---|---|---|---|---|")
    for e in sorted(plaud, key=lambda x: (not x.get("official", False), str(x.get("author","")).lower(), str(x.get("name","")).lower())):
        lines.append(
            "| `{id}` | {name} | {author} | {official} | {category} | {source} |".format(
                id=e.get("id", ""),
                name=e.get("name", ""),
                author=e.get("author", ""),
                official=e.get("official", False),
                category=e.get("category", ""),
                source=e.get("source", ""),
            )
        )
    lines.append("")
    lines.append("### Authors")
    lines.append("")
    authors = Counter(e.get("author", "Unknown") for e in plaud)
    for author, n in sorted(authors.items(), key=lambda kv: kv[0].lower()):
        lines.append(f"- **{author}** — {n} template(s)")
lines.append("")

with open(credits_path, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")
print(f"Wrote {credits_path}")
PY

echo "Synced $PLAUD_COUNT Plaud + $CONTRIB_COUNT contributed → $RES_DIR and $CREDITS"
