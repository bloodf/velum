#!/usr/bin/env python3
"""
Apply exact-body dedupe (#99) to the shipped catalogs in place.

Reads the gzip Full set, collapses identical bodies with `clean.dedupe_exact_bodies`,
rewrites the gzip (deterministic: mtime=0, curate sort order), rewrites each Featured
JSONL from survivors flagged `featured`, merges removed→survivor ids into the generated
Kotlin alias map, and refreshes `catalog_report.json`. Running it twice changes nothing.
"""
from __future__ import annotations

import argparse
import gzip
import json
import re
import sys
from collections import Counter
from pathlib import Path

from clean import dedupe_exact_bodies
from curate import CATEGORY_ORDER, quality_score

ROOT = Path(__file__).resolve().parent.parent.parent
RES = ROOT / "core" / "src" / "commonMain" / "resources"
ALIAS_RE = re.compile(r'^\s*"([A-Za-z0-9._-]+)" to "([A-Za-z0-9._-]+)",$', re.M)
SAFE_ID = re.compile(r"^[A-Za-z0-9._-]+$")


def read_jsonl(path: Path) -> list[dict]:
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip() and not line.startswith("#")]


def dump(rows: list[dict]) -> str:
    return "".join(json.dumps(r, ensure_ascii=False, separators=(",", ":")) + "\n" for r in rows)


def sort_key(r: dict) -> tuple:
    cat = r["category"]
    return (CATEGORY_ORDER.index(cat) if cat in CATEGORY_ORDER else 99, -quality_score(r), r["id"])


def read_aliases(path: Path) -> dict[str, str]:
    return dict(ALIAS_RE.findall(path.read_text(encoding="utf-8"))) if path.exists() else {}


def write_aliases(path: Path, aliases: dict[str, str]) -> None:
    for k, v in aliases.items():
        if not (SAFE_ID.match(k) and SAFE_ID.match(v)):
            raise ValueError(f"unsafe template id in alias {k!r} -> {v!r}")
    body = "".join(f'        "{k}" to "{v}",\n' for k, v in sorted(aliases.items()))
    path.write_text(
        "// Generated by tools/templates/dedupe_catalog.py — do not edit by hand.\n"
        "package dev.velum.core.templates\n\n"
        "/**\n"
        " * Builtin template ids removed as exact-body duplicates (#99) → retained survivor id.\n"
        " * Entries are never dropped so old AutoFlows, queued jobs and summary versions resolve.\n"
        " */\n"
        "object PlaudTemplateAliases {\n"
        "    val RemovedDuplicates: Map<String, String> = mapOf(\n"
        f"{body}"
        "    )\n"
        "}\n",
        encoding="utf-8",
    )


def run(*, full: Path, featured: list[Path], aliases_kt: Path, report: Path | None) -> dict:
    rows = read_jsonl(full)
    featured_ids = frozenset(r["id"] for p in featured for r in read_jsonl(p))
    res = dedupe_exact_bodies(rows, featured_ids)
    full_out = sorted(
        (dict(r, featured=r.get("featured") or r["id"] in featured_ids) for r in res.survivors),
        key=sort_key,
    )
    featured_out = [r for r in full_out if r["featured"]]

    with full.open("wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", compresslevel=9, mtime=0, filename="") as gz:
        gz.write(dump(full_out).encode("utf-8"))
    for p in featured:
        p.write_text(dump(featured_out), encoding="utf-8")

    # Keep old aliases; repoint any whose survivor was itself removed this run.
    retained = {r["id"] for r in full_out}
    aliases = {**read_aliases(aliases_kt), **res.aliases}
    for k, v in list(aliases.items()):
        seen = {k}
        while v not in retained and v in aliases and v not in seen:
            seen.add(v)
            v = aliases[v]
        aliases[k] = v
    write_aliases(aliases_kt, aliases)

    summary = {
        "input_rows": res.input_rows,
        "duplicate_body_groups": res.duplicate_groups,
        "removed_rows": res.removed_rows,
        "output_rows": len(full_out),
        "featured_rows": len(featured_out),
        "aliases_total": len(aliases),
    }
    if report is not None:
        data = json.loads(report.read_text(encoding="utf-8")) if report.exists() else {}
        per_cat = Counter(r["category"] for r in full_out)
        feat_cat = Counter(r["category"] for r in featured_out)
        data.update(
            featured_total=len(featured_out),
            featured_per_category={c: feat_cat.get(c, 0) for c in CATEGORY_ORDER},
            full_total=len(full_out),
            full_per_category={c: per_cat.get(c, 0) for c in CATEGORY_ORDER},
            official_in_featured=sum(1 for r in featured_out if r.get("official")),
            official_in_full=sum(1 for r in full_out if r.get("official")),
        )
        report.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return summary


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--full", type=Path, default=RES / "plaud_templates_full.jsonl.gz")
    p.add_argument(
        "--featured",
        type=Path,
        action="append",
        help="Featured JSONL to rewrite (repeatable). Default: docs + resources copies.",
    )
    p.add_argument(
        "--aliases-kt",
        type=Path,
        default=ROOT / "core/src/commonMain/kotlin/dev/velum/core/templates/PlaudTemplateAliases.kt",
    )
    p.add_argument("--report", type=Path, default=ROOT / "docs/templates/catalog_report.json")
    args = p.parse_args(argv)
    featured = args.featured or [ROOT / "docs/templates/plaud_templates.jsonl", RES / "plaud_templates.jsonl"]
    summary = run(full=args.full, featured=featured, aliases_kt=args.aliases_kt, report=args.report)
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
